import logging
from collections import defaultdict
from math import copysign

from odoo import fields, models

_logger = logging.getLogger(__name__)


class AccountMoveLine(models.Model):
    _inherit = "account.move.line"

    # Adds a direct link to the off-balance and on-balance associated lines
    on_balance_line_ids = fields.Many2many(
        "account.move.line",
        "account_move_line_off_balance_rel",
        "off_balance_line_id",
        "on_balance_line_id",
        string="On-Balance Lines",
        help="Lines generated on-balance from this off-balance line.",
    )
    off_balance_line_ids = fields.Many2many(
        "account.move.line",
        "account_move_line_off_balance_rel",
        "on_balance_line_id",
        "off_balance_line_id",
        string="Off-Balance Line",
        help="Link to the off-balance lines associated with this on-balance line.",
    )
    is_off_balance_generated = fields.Boolean(
        help="Technical field used to identify lines generated by the off-balance "
        "reconciliation process.",
    )
    off_balance_amount = fields.Monetary(
        compute="_compute_off_balance_amount",
        string="Off-Balance Amount",
        currency_field="currency_id",
        help=(
            "For off-balance lines: Total amount not yet distributed on on-balance "
            "accounts.\n"
            "For on-balance lines: Total amount associated with off-balance lines."
        ),
    )

    def _compute_off_balance_amount(self):
        for line in self:
            related_lines = (
                line.on_balance_line_ids
                if line.account_id.is_off_balance
                else line.off_balance_line_ids
            )
            related_total = (
                copysign(sum(related_lines.mapped("balance")), line.balance)
                if related_lines
                else 0.0
            )
            if line.account_id.is_off_balance:
                line.off_balance_amount = line.balance - related_total
            else:
                line.off_balance_amount = related_total

    def _search(self, domain, offset=0, limit=None, order=None, access_rights_uid=None):
        if self.env.context.get("filter_off_balance"):
            domain.append(("account_id.is_off_balance", "=", False))
        return super()._search(domain, offset, limit, order, access_rights_uid)

    def _reconcile_post_hook(self, data):
        super()._reconcile_post_hook(data)
        income_off_balance = self.move_id.line_ids.filtered(
            lambda move_line: move_line.account_id.is_off_balance
            and move_line.company_id.off_balance_asset_account_id
        )
        if income_off_balance:
            self._register_off_balance_income()

    def _register_off_balance_income(self):
        """
        When an income is reconciled, we look if it was linked to a donation invoiced
        on the off-balance account. If so, we create the corresponding lines on the
        on-balance account.

        We cover the following scenarios:
        1. The income is directly reconciled with an invoice
        2. The income is reconciled with a debit order connected with the invoice
           a. Full reconciliation
           b. Partial reconciliation

        :param self: The reconciled lines
        :return: True if lines were created, False otherwise
        """
        # Step 1: Get income move lines
        income_move_lines = self._get_income_move_lines()
        if not income_move_lines:
            _logger.debug("No income move lines found for off-balance registration")
            return False

        # Step 2: Get related invoice lines
        invoice_lines = self._get_related_invoice_lines()

        # Step 3: Validate off-balance lines exist
        off_balance_lines = invoice_lines.filtered("account_id.is_off_balance")
        if not off_balance_lines:
            _logger.debug("No off-balance credit lines found")
            return False

        # Step 4: Build on-balance amounts by account and product
        onbalance_amounts_by_account = self._build_onbalance_amounts(
            invoice_lines, income_move_lines
        )

        if not onbalance_amounts_by_account:
            _logger.debug("No on-balance amounts to process")
            return False

        # Step 5: Create on-balance move lines
        income_entry = income_move_lines.move_id[0]
        self._create_onbalance_move_lines(
            onbalance_amounts_by_account,
            income_entry,
        )

        amount_distributed = sum(
            income_entry.line_ids.filtered(
                lambda mvl: mvl.is_off_balance_generated
                and mvl.account_id.is_off_balance
            ).mapped("balance")
        )
        _logger.info(
            "Created off-balance adjustment for move %s, amount: %s",
            income_entry.name,
            amount_distributed,
        )
        return True

    def _get_income_move_lines(self):
        """
        Extract income move lines: those with asset accounts credited
        linked to the reconciled receivable lines.
        (should not be an outstanding payment)

        :return: Recordset of income move lines
        """
        return self.move_id.line_ids.filtered(
            lambda line: line.move_type == "entry"
            and line.account_internal_group == "asset"
            and line.credit
            and not line.payment_id
        )

    def _get_related_invoice_lines(self):
        """
        Get invoice lines related to the reconciled lines.

        Handles two scenarios:
        - Direct reconciliation with invoices
        - Reconciliation through debit orders

        :return: Recordset of invoice lines sorted by invoice total amount
                 (so that invoices have a chance to be fully processed
                 if the total amount is not enough)
        """
        invoices = self.filtered(
            lambda mvl: mvl.move_type in ("out_invoice", "out_refund")
        ).move_id
        if invoices:
            # Scenario 1: Direct reconciliation with invoice
            return invoices.sorted("amount_total").mapped("invoice_line_ids")
        else:
            # Scenario 2: Reconciliation through debit order
            # Fetch all reconciled lines and filter invoices
            all_reconciled_lines = (
                self.move_id.line_ids.full_reconcile_id.reconciled_line_ids
            )
            return (
                all_reconciled_lines.move_id.filtered(
                    lambda m: m.move_type in ("out_invoice", "out_refund")
                )
                .sorted("amount_total")
                .mapped("invoice_line_ids")
            )

    def _build_onbalance_amounts(self, invoice_lines, income_move_lines):
        """
        Build a dictionary of on-balance amounts grouped by invoice line.

        :param invoice_lines: Invoice lines to process
        :param income_move_lines: Income move lines
        :return: Tuple of (amounts_dict, total_amount)
        """
        onbalance_amounts_by_line = defaultdict(float)
        total_income = abs(sum(income_move_lines.mapped("balance")))
        total_already_distributed = abs(
            sum(invoice_lines.mapped("on_balance_line_ids.balance"))
        )
        available_income = total_income - total_already_distributed

        # Process invoice lines with on-balance accounts
        for invoice_line in invoice_lines.filtered(
            lambda line: line.account_id.on_balance_account_id
        ):
            remaining_amount = invoice_line.price_total
            if invoice_line.on_balance_line_ids:
                already_distributed = copysign(
                    sum(invoice_line.on_balance_line_ids.mapped("balance")),
                    remaining_amount,
                )
                remaining_amount -= already_distributed
            if invoice_line.currency_id.is_zero(remaining_amount):
                continue

            ratio = invoice_line.move_id._compute_invoice_distribution_ratio(
                available_income
            )
            distributed_amount = copysign(
                min(abs(remaining_amount) * ratio, available_income),
                invoice_line.balance,
            )
            if invoice_line.currency_id.is_zero(distributed_amount):
                continue

            onbalance_amounts_by_line[invoice_line] = distributed_amount
            available_income -= abs(distributed_amount)
            if invoice_line.currency_id.is_zero(available_income):
                break
        return onbalance_amounts_by_line

    def _create_onbalance_move_lines(
        self,
        onbalance_amounts_by_account,
        income_entry,
    ):
        """
        Create on-balance move lines based on prorated distribution.

        :param onbalance_amounts_by_account: Dict of amounts by account and product
        :param income_entry: The income journal entry
        """
        # Prepare line creation
        total_distributed_amount = 0.0
        total_offbalance_amount = sum(onbalance_amounts_by_account.values())
        currency = income_entry.currency_id
        lines_to_create = defaultdict(
            lambda: {
                "move_id": income_entry.id,
                "partner_id": income_entry.partner_id.id,
                "is_off_balance_generated": True,
                "name": "Off-Balance Adjustment",
                "off_balance_line_ids": [],
            }
        )

        # Create prorated lines for each account/product combination
        for (
            invoice_line,
            remaining_amount,
        ) in onbalance_amounts_by_account.items():
            prorated_amount = remaining_amount
            distributed_amount = currency.round(prorated_amount)
            key = (
                invoice_line.account_id.on_balance_account_id.id,
                invoice_line.product_id.id or False,
            )
            lines_to_create[key].update(
                {
                    "account_id": key[0],
                    "product_id": key[1],
                    "balance": distributed_amount,
                }
            )
            lines_to_create[key]["off_balance_line_ids"].append((4, invoice_line.id))
            total_distributed_amount += distributed_amount

        # Apply rounding adjustment to the last line
        if lines_to_create:
            rounding_adjustment = currency.round(
                total_offbalance_amount - total_distributed_amount
            )
            if rounding_adjustment:
                list(lines_to_create.values())[-1]["balance"] += rounding_adjustment
                total_distributed_amount += rounding_adjustment

            # Create the on-balance lines
            on_balance_lines = self.with_context(check_move_validity=False).create(
                list(lines_to_create.values())
            )

            # Create the off-balance asset line
            self._create_offbalance_asset_line(
                income_entry, currency, total_distributed_amount, on_balance_lines.ids
            )

    def _create_offbalance_asset_line(
        self, income_entry, currency, amount, on_balance_line_ids
    ):
        """
        Create an account move line reflecting the reconciliation amount
        on the off-balance asset account.

        :param income_entry: The income journal entry
        :param currency: The currency for rounding
        :param amount: The total distributed amount (negative for income)
        :param on_balance_line_ids: List of created on-balance line IDs
        """
        self.env["account.move.line"].with_context(check_move_validity=False).create(
            {
                "account_id": income_entry.company_id.off_balance_asset_account_id.id,
                "name": "Off-Balance Adjustment",
                "move_id": income_entry.id,
                "partner_id": income_entry.partner_id.id,
                "balance": currency.round(-amount),  # Negative to balance the credits
                "is_off_balance_generated": True,
                "on_balance_line_ids": [(6, 0, on_balance_line_ids)],
            }
        )

    def _prepare_exchange_difference_move_vals(
        self, amounts_list, company=None, exchange_date=None, **kwargs
    ):
        """
        Replace the exchange rate diff account with the off balance account
        if the income is off-balance.
        """
        res = super()._prepare_exchange_difference_move_vals(
            amounts_list, company=company, exchange_date=exchange_date, **kwargs
        )

        for i, line in enumerate(self):
            exchange_vals = res["move_values"]["line_ids"][((i + 1) * 2) - 1]
            if line.account_id.is_off_balance:
                exchange_account_id = exchange_vals[2]["account_id"]
                off_balance_exchange_account = self.env["account.account"].search(
                    [("on_balance_account_id", "=", exchange_account_id)], limit=1
                )
                if off_balance_exchange_account:
                    exchange_vals[2]["account_id"] = off_balance_exchange_account.id
                    exchange_vals[2]["is_off_balance_generated"] = True

        return res
